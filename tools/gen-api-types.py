#!/usr/bin/env python3
"""
Generate webui/src/api.d.ts from the websocket API registry (manager/api/ws/endpoints.py: WebSocketAPI.schema).

The runtime client (webui/src/api.js) needs no declarations at all; this file only gives editors completion
and argument checking for `api.Settings.Audio.volume({...})`. Run it after adding or changing an API function:

    .venv/bin/python tools/gen-api-types.py
"""
import asyncio
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.argv = sys.argv[:1]
sys.path.insert(0, str(ROOT / 'manager'))
# importing the API builds the upload manager, which wants an event loop and its folder
asyncio.set_event_loop(asyncio.new_event_loop())
pathlib.Path.mkdir = lambda *a, **k: None

from api.ws.endpoints import api  # noqa: E402


def ts_type(schema: dict, defs: dict) -> str:
    if '$ref' in schema:
        return ts_type(defs.get(schema['$ref'].split('/')[-1], {}), defs)
    if 'enum' in schema:
        return ' | '.join(repr(v).replace("'", '"') if isinstance(v, str) else str(v).lower() for v in schema['enum'])
    for key in ('anyOf', 'oneOf'):
        if key in schema:
            return ' | '.join(sorted({ts_type(s, defs) for s in schema[key]}))
    kind = schema.get('type')
    if kind in ('integer', 'number'):
        return 'number'
    if kind == 'string':
        return 'string'
    if kind == 'boolean':
        return 'boolean'
    if kind == 'null':
        return 'null'
    if kind == 'array':
        return f"({ts_type(schema.get('items', {}), defs)})[]"
    if kind == 'object' and 'properties' in schema:
        return '{ ' + '; '.join(f'{k}{"" if k in schema.get("required", []) else "?"}: {ts_type(v, defs)}'
                                for k, v in schema['properties'].items()) + ' }'
    return 'any'


def main():
    tree: dict = {}
    for path, info in api.schema.items():
        params = info['params']
        defs = params.get('$defs', {})
        args = ts_type({**params, 'type': 'object'}, defs) if params.get('properties') else 'Record<string, never>'
        node = tree
        *parents, leaf = path.split('/')
        for part in parents:
            node = node.setdefault(part, {})
        node[leaf] = (args, info['doc'], info['permissions'])

    def emit(node, indent):
        pad = '  ' * indent
        lines = []
        for key, value in node.items():
            if isinstance(value, tuple):
                args, doc, perms = value
                comment = ' '.join(filter(None, [doc.splitlines()[0] if doc else '', f'[requires: {", ".join(perms)}]' if perms else '']))
                if comment:
                    lines.append(f'{pad}/** {comment} */')
                lines.append(f'{pad}{key}: ApiCall<{args}>')
            else:
                lines.append(f'{pad}{key}: {{')
                lines.extend(emit(value, indent + 1))
                lines.append(f'{pad}}}')
        return lines

    out = ['// Generated by tools/gen-api-types.py - do not edit by hand.',
           'export type ApiMessage = { target: string; [key: string]: any }',
           'export type ApiCall<P> = ((args?: P) => void) & {',
           '  /** Runs the callback for each message the server sends for this function (also for other clients\' calls). */',
           '  on(callback: (data: ApiMessage) => void, options?: { init?: boolean }): void',
           '  /** A ref with the last message (or its `pick` field); asks the server for it unless init is false. */',
           '  use(options?: { pick?: string; init?: boolean; initial?: any }): import(\'vue\').Ref<any>',
           '}',
           'export interface Api {',
           *emit(tree, 1),
           '}',
           'export const api: Api',
           '']
    (ROOT / 'webui/src/api.d.ts').write_text('\n'.join(out))
    print(f'{len(api.schema)} functions written to webui/src/api.d.ts')


main()
